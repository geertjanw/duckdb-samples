package org.example;

import com.sun.net.httpserver.HttpExchange;
import com.sun.net.httpserver.HttpServer;
import org.graalvm.polyglot.Context;
import org.graalvm.polyglot.Value;

import java.io.IOException;
import java.io.OutputStream;
import java.net.InetSocketAddress;
import java.nio.charset.StandardCharsets;

/**
 * Serves one page and one data endpoint. DuckDB-Wasm runs the SQL in the
 * browser; the CSV it queries is produced by Python running on GraalPy, in
 * this JVM. Nothing in the backend touches a Java data library.
 */
public class Server {

    public static void main(String[] args) throws IOException {
        byte[] page = read("/index.html");
        String script = new String(read("/generate.py"), StandardCharsets.UTF_8);

        // One Python context, built once and reused. allowAllAccess lets the
        // script import the stdlib it needs (random); execute() is serialized
        // below because a polyglot context is used from one thread at a time.
        Context python = Context.newBuilder("python").allowAllAccess(true).build();
        python.eval("python", script);
        Value salesCsv = python.getBindings("python").getMember("sales_csv");

        HttpServer server = HttpServer.create(new InetSocketAddress(8080), 0);

        server.createContext("/api/sales.csv", exchange -> {
            String csv;
            synchronized (python) {
                csv = salesCsv.execute(1000).asString();
            }
            send(exchange, "text/csv; charset=utf-8", csv.getBytes(StandardCharsets.UTF_8));
        });

        server.createContext("/", exchange -> send(exchange, "text/html; charset=utf-8", page));

        server.start();
        System.out.println("Serving http://localhost:8080  (CSV generated by Python on GraalPy)");
    }

    private static void send(HttpExchange exchange, String contentType, byte[] body) throws IOException {
        exchange.getResponseHeaders().set("Content-Type", contentType);
        exchange.sendResponseHeaders(200, body.length);
        try (OutputStream out = exchange.getResponseBody()) {
            out.write(body);
        }
    }

    private static byte[] read(String resource) throws IOException {
        try (var in = Server.class.getResourceAsStream(resource)) {
            if (in == null) {
                throw new IOException("missing resource " + resource);
            }
            return in.readAllBytes();
        }
    }
}
